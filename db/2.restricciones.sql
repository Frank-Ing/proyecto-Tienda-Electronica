ALTER TABLE administrador
    ALTER COLUMN identificador ADD GENERATED BY DEFAULT AS IDENTITY,
    ALTER COLUMN identificador SET NOT NULL,
    ADD CONSTRAINT pk_administrador PRIMARY KEY (identificador),
    ADD CONSTRAINT uq_administrador_usuario UNIQUE (usuario),
    ALTER COLUMN usuario SET NOT NULL,
    ALTER COLUMN usuario SET DEFAULT 'Frankcode',
    ALTER COLUMN contrasena SET NOT NULL,
    ADD CONSTRAINT chk_administrador_usuario_longitud
        CHECK (CHAR_LENGTH(usuario) <= 15),
    ADD CONSTRAINT chk_administrador_contrasena_longitud
        CHECK (CHAR_LENGTH(contrasena) <= 60);

ALTER TABLE producto
    ADD COLUMN IF NOT EXISTS imagen_url TEXT,
    ALTER COLUMN identificador_producto ADD GENERATED BY DEFAULT AS IDENTITY,
    ALTER COLUMN identificador_producto SET NOT NULL,
    ADD CONSTRAINT pk_producto PRIMARY KEY (identificador_producto),
    ALTER COLUMN modelo_producto SET NOT NULL,
    ALTER COLUMN precio SET NOT NULL,
    ALTER COLUMN stock SET NOT NULL,
    ALTER COLUMN categoria SET NOT NULL,
    ALTER COLUMN precio SET DEFAULT 1.00,
    ALTER COLUMN stock SET DEFAULT 0,
    ADD CONSTRAINT chk_producto_precio_positivo
        CHECK (precio > 0),
    ADD CONSTRAINT chk_producto_stock_no_negativo
        CHECK (stock >= 0),
    ADD CONSTRAINT chk_producto_categoria_valida
        CHECK (categoria IN ('celular', 'laptop', 'monitor', 'teclado', 'mouse', 'audifonos')),
    ADD CONSTRAINT chk_producto_imagen_url_valida
        CHECK (imagen_url IS NULL OR imagen_url ~* '^https?://');
